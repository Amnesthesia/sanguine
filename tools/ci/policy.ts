// The two policy documents as data the app can show (PLAN.md §2.4, §2.5). The app never fetches them: they are generated from docs/ into the bundle.
// A document with an unfilled "TBD (human)" is not ready: the app does not show it, so a draft never reaches a user.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(__dirname, '..', '..');
export const POLICY_SOURCES = { privacy: 'docs/privacy-policy.md', consumerHealth: 'docs/consumer-health-data-policy.md' } as const;
export const POLICY_OUT = join(ROOT, 'apps', 'mobile', 'src', 'features', 'legal', 'policies.generated.ts');

export interface Block { type: 'h' | 'p' | 'li'; text: string }
export interface Policy { title: string; blocks: Block[]; ready: boolean }

const plain = (s: string) => s.replace(/\*\*(.+?)\*\*/g, '$1').replace(/`(.+?)`/g, '$1').replace(/\[(.+?)\]\((.+?)\)/g, '$1 ($2)').trim();

export function parsePolicy(md: string): Policy {
  let title = '';
  const blocks: Block[] = [];
  let para: string[] = [];
  const flush = () => { if (para.length) blocks.push({ type: 'p', text: plain(para.join(' ')) }); para = []; };
  for (const raw of md.split('\n')) {
    const line = raw.trimEnd();
    if (line.trim() === '') { flush(); continue; }
    if (/^DRAFT\b/i.test(line)) continue; // the draft banner is for the repository, not the app
    if (line.startsWith('# ')) { flush(); title = plain(line.slice(2)); }
    else if (/^#{2,3} /.test(line)) { flush(); blocks.push({ type: 'h', text: plain(line.replace(/^#+ /, '')) }); }
    else if (/^\s*(?:[-*]|\d+\.)\s+/.test(line)) { flush(); blocks.push({ type: 'li', text: plain(line.replace(/^\s*(?:[-*]|\d+\.)\s+/, '')) }); }
    else if (/^\|[\s|:-]+$/.test(line)) { flush(); } // the separator row of a table
    else if (line.startsWith('|')) { flush(); blocks.push({ type: 'p', text: plain(line.replace(/\|/g, ' ').replace(/\s{2,}/g, ' ')) }); }
    else para.push(line.trim());
  }
  flush();
  return { title, blocks, ready: !/TBD \(human\)/.test(md) };
}

export function renderPolicies(read: (p: string) => string = (p) => readFileSync(join(ROOT, p), 'utf8')): string {
  const data = Object.fromEntries(Object.entries(POLICY_SOURCES).map(([k, p]) => [k, parsePolicy(read(p))]));
  return `// Generated by \`pnpm policy\` (tools/ci/policy.ts) from docs/*.md. Do not edit by hand.\nexport const POLICIES = ${JSON.stringify(data, null, 2)} as const;\n`;
}

if (require.main === module) { writeFileSync(POLICY_OUT, renderPolicies()); console.log(`wrote ${POLICY_OUT}`); }
