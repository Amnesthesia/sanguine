// Generates docs/regulatory/soup.md: third-party packages (SOUP, IEC 62304) with resolved versions.
// Run: pnpm soup   (CI runs soup.test.ts, which fails if the committed file is stale.)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(__dirname, '..', '..');
export const SOUP_PATH = join(root, 'docs', 'regulatory', 'soup.md');
const WORKSPACES = ['apps/mobile', 'packages/engine', 'packages/crypto', 'packages/ui-tokens', 'packages/health-adapter', 'tools/backtest', 'tools/brand', '.'];

function installedVersion(name: string): string {
  const f = join(root, 'node_modules', name, 'package.json');
  return existsSync(f) ? (JSON.parse(readFileSync(f, 'utf8')).version as string) : 'not installed';
}

export function renderSoup(): string {
  const rows = new Map<string, { range: string; used: Set<string>; dev: boolean }>();
  for (const ws of WORKSPACES) {
    const p = JSON.parse(readFileSync(join(root, ws, 'package.json'), 'utf8'));
    for (const [kind, deps] of [['runtime', p.dependencies], ['dev', p.devDependencies]] as const)
      for (const [name, range] of Object.entries<string>(deps ?? {})) {
        if (name.startsWith('@sanguine/')) continue;
        const r = rows.get(name) ?? { range, used: new Set<string>(), dev: true };
        r.used.add(ws === '.' ? 'root' : ws);
        if (kind === 'runtime') r.dev = false;
        rows.set(name, r);
      }
  }
  const lines = [...rows.entries()].sort(([a], [b]) => a.localeCompare(b)).map(
    ([name, r]) => `| ${name} | ${installedVersion(name)} | ${r.range} | ${r.dev ? 'dev/build only' : 'ships in app'} | ${[...r.used].sort().join(', ')} |`,
  );
  return [
    '# SOUP list (software of unknown provenance)',
    '',
    'Generated by `pnpm soup` from the workspace `package.json` files and installed versions. Do not edit by hand.',
    'Engine-affecting packages are those used by `packages/engine`: it has no runtime dependencies (a test enforces this).',
    '',
    '| Package | Installed | Range | Role | Used by |',
    '| --- | --- | --- | --- | --- |',
    ...lines,
    '',
  ].join('\n');
}

if (process.argv[1] && /soup\.ts$/.test(process.argv[1])) writeFileSync(SOUP_PATH, renderSoup());
