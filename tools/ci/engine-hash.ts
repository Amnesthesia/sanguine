// Writes packages/engine/src/buildInfo.ts: SHA-256 over the engine's non-test sources (sorted by name).
// Shown in Settings > About so anyone can check it against the repo (PLAN.md §6.7). Run: pnpm engine-hash
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(__dirname, '..', '..', 'packages', 'engine', 'src');
export const BUILD_INFO_PATH = join(dir, 'buildInfo.ts');

export function engineSourceHash(): string {
  const h = createHash('sha256');
  const files = readdirSync(dir).filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts') && f !== 'buildInfo.ts' && f !== 'fixtures.ts').sort();
  for (const f of files) { h.update(f); h.update('\0'); h.update(readFileSync(join(dir, f))); h.update('\0'); }
  return h.digest('hex');
}

export function renderBuildInfo(): string {
  return `// Generated by tools/ci/engine-hash.ts (pnpm engine-hash). Do not edit.\nexport const ENGINE_BUILD_HASH = '${engineSourceHash()}';\n`;
}

if (process.argv[1] && /engine-hash\.ts$/.test(process.argv[1])) writeFileSync(BUILD_INFO_PATH, renderBuildInfo());
